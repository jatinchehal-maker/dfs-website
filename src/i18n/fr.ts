/** Patterns for messages built at runtime (form validation). */
export const FR_PATTERNS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^(.+) is required$/, (m) => `${FR[m[1]] ?? m[1]} : champ obligatoire`],
  [/^(Open|Close) (\d)\. (.+), (\d+) items?$/, (m) => `${m[1] === "Open" ? "Ouvrir" : "Fermer"} ${FR[`${m[2]}. ${m[3]}`] ?? `${m[2]}. ${m[3]}`}, ${m[4]} éléments`],
  [/^(\d)\. (.+) contents$/, (m) => `Contenu de ${FR[`${m[1]}. ${m[2]}`] ?? m[2]}`],
  [/^Enter a valid (.+)$/, (m) => `Entrez une valeur valide (${(FR[cap(m[1])] ?? m[1]).toLowerCase()})`],
];

function cap(s: string) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
